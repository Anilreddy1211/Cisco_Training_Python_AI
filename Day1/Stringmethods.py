text = "python programming"

print("1. upper()     :", text.upper())
print("2. lower()     :", text.lower())
print("3. title()     :", text.title())
print("4. capitalize():", text.capitalize())
print("5. count()     :", text.count("p"))
print("6. startswith():", text.startswith("python"))
print("7. endswith()  :", text.endswith("ing"))
print("8. find()      :", text.find("programming"))
print("9. replace()   :", text.replace("python", "Java"))
print("10. split()    :", text.split())
